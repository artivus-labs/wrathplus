//! The stock API's docs table (`$OUT_DIR/stock_api.rs`), read off our own bindings in
//! `wrathplus-ui/src/script` by [`stock_extract`], with the arity census's reviewed notes. Built
//! from source every time it changes, so it cannot drift from the bindings; `stock_api_tests`
//! checks it against the names a fresh UI VM registers.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

#[path = "src/stock_extract.rs"]
#[allow(dead_code)]
mod stock_extract;

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs" || e == "lua") {
            out.push(path);
        }
    }
}

fn main() {
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let script = crates.join("wrathplus-ui/src/script");
    let census = crates.join("wrathplus-app-ui/src/ui_script/wrath_census_arity.rs");
    println!("cargo:rerun-if-changed={}", script.display());
    println!("cargo:rerun-if-changed={}", census.display());
    println!("cargo:rerun-if-changed=src/stock_extract.rs");

    let mut files = Vec::new();
    walk(&script, &mut files);
    files.sort();
    let mut found = BTreeMap::new();
    for path in &files {
        let rel = path.strip_prefix(&crates).unwrap_or(path);
        let rel = format!("crates/{}", rel.to_string_lossy().replace('\\', "/"));
        if stock_extract::is_test_path(&rel) {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(path) else {
            continue;
        };
        if rel.ends_with(".lua") {
            stock_extract::scan_lua(&rel, &text, &mut found);
        } else {
            stock_extract::scan_rust(&rel, &text, &mut found);
        }
    }
    let notes = std::fs::read_to_string(&census)
        .map(|t| stock_extract::census_notes(&t))
        .unwrap_or_default();

    let mut out = String::from(
        "/// Generated by build.rs from wrathplus-ui's bindings: one [`Row`] per name, sorted by name.\n\
         pub(crate) static STOCK_API: &[Row] = &[\n",
    );
    for f in found.values() {
        let note = notes.get(&f.name).map_or("", String::as_str);
        out.push_str(&format!(
            "    ({:?}, {:?}, {:?}, {:?}, {:?}),\n",
            f.name, f.at, f.doc, note, f.source
        ));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("stock_api.rs");
    std::fs::write(dest, out).expect("write stock_api.rs");
}
