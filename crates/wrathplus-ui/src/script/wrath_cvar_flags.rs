/// The flag bits 4..=6 of the CVar named `name` (any case), 0 for a row registered with none.
pub(super) fn flags(name: &str) -> u8 {
    let key = name.to_ascii_lowercase();
    FLAGS
        .binary_search_by(|(n, _)| (*n).cmp(key.as_str()))
        .map_or(0, |i| FLAGS[i].1)
}

