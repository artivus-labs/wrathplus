mod tests {
    #[test]
    fn the_table_is_sorted_and_answers_any_case() {
        assert!(super::FLAGS.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(super::flags("autoLootDefault"), 0x10);
        assert_eq!(super::flags("AUTOSELFCAST"), 0x20);
        assert_eq!(super::flags("accountName"), 0x40);
        assert_eq!(super::flags("gxResolution"), 0);
    }
}
